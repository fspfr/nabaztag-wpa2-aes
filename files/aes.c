/* Forward S-box (inverse of invsbox, computed once) */
static uint8_t fwdbox[256];
static uint8_t fwdbox_inited = 0;

static const uint8_t rcon[11] = {
0x00,0x01,0x02,0x04,0x08,0x10,0x20,0x40,0x80,0x1b,0x36
};

#define GETU32(p) ((uint32_t)(((p)[0]<<24) | ((p)[1]<<16) | ((p)[2]<<8) | (p)[3]))
#define PUTU32(p,v) do{ (p)[0]=(uint8_t)((v)>>24); (p)[1]=(uint8_t)((v)>>16); \
                       (p)[2]=(uint8_t)((v)>>8); (p)[3]=(uint8_t)(v); }while(0)

static uint8_t xtime(uint8_t x)
{
	return (uint8_t)((x<<1) ^ ((x>>7)*0x1b));
}

static uint8_t gmul(uint8_t a, uint8_t b)
{
	uint8_t p = 0;
	while(b) {
		if(b & 1) p ^= a;
		a = xtime(a);
		b >>= 1;
	}
	return p;
}

static void inv_mix_column(uint8_t *c)
{
	uint8_t a0=c[0], a1=c[1], a2=c[2], a3=c[3];
	c[0] = (uint8_t)(gmul(a0,14) ^ gmul(a1,11) ^ gmul(a2,13) ^ gmul(a3, 9));
	c[1] = (uint8_t)(gmul(a0, 9) ^ gmul(a1,14) ^ gmul(a2,11) ^ gmul(a3,13));
	c[2] = (uint8_t)(gmul(a0,13) ^ gmul(a1, 9) ^ gmul(a2,14) ^ gmul(a3,11));
	c[3] = (uint8_t)(gmul(a0,11) ^ gmul(a1,13) ^ gmul(a2, 9) ^ gmul(a3,14));
}

static void inv_shift_rows(const uint8_t in[16], uint8_t out[16])
{
	int c, r;
	for(r=0;r<4;r++)
		for(c=0;c<4;c++)
			out[4*c+r] = in[4*((c-r+4)&3)+r];
}

void aes128_decrypt_block(const uint8_t *key, uint8_t block[16])
{
	uint32_t rk[44];
	uint8_t s[16], t[16];
	uint32_t w;
	int i, r;

	if(!fwdbox_inited) {
		for(i=0;i<256;i++)
			fwdbox[invsbox[i]] = (uint8_t)i;
		fwdbox_inited = 1;
	}

	/* Key expansion (AES-128: 44 words) */
	for(i=0;i<4;i++)
		rk[i] = GETU32(key+4*i);
	for(i=4;i<44;i++) {
		w = rk[i-1];
		if((i & 3) == 0) {
			uint8_t b[4];
			b[0]=fwdbox[(uint8_t)(w>>16)];
			b[1]=fwdbox[(uint8_t)(w>>8)];
			b[2]=fwdbox[(uint8_t)w];
			b[3]=fwdbox[(uint8_t)(w>>24)];
			w = ((uint32_t)b[0]<<24) | ((uint32_t)b[1]<<16) |
			    ((uint32_t)b[2]<<8) | (uint32_t)b[3];
			w ^= (uint32_t)rcon[i/4] << 24;
		}
		rk[i] = rk[i-4] ^ w;
	}

	/* AddRoundKey(10) */
	for(i=0;i<4;i++) {
		uint32_t v = GETU32(block+4*i) ^ rk[40+i];
		PUTU32(s+4*i, v);
	}

	/* Undo the final (partial) encryption round */
	inv_shift_rows(s, t);
	memcpy(s, t, 16);
	for(i=0;i<16;i++) s[i] = invsbox[s[i]];

	/* Rounds 9 down to 1: AddRoundKey FIRST, then InvMixColumns,
	 * InvShiftRows, InvSubBytes (direct inverse of the encryption
	 * round: state_r = mix(shift(sub(state_{r-1}))) XOR rk_r) */
	for(r=9;r>=1;r--) {
		for(i=0;i<4;i++) {
			uint32_t v = GETU32(s+4*i) ^ rk[r*4+i];
			PUTU32(s+4*i, v);
		}
		for(i=0;i<4;i++) inv_mix_column(s+4*i);
		inv_shift_rows(s, t);
		memcpy(s, t, 16);
		for(i=0;i<16;i++) s[i] = invsbox[s[i]];
	}

	/* AddRoundKey(0) */
	for(i=0;i<4;i++) {
		uint32_t v = GETU32(s+4*i) ^ rk[i];
		PUTU32(s+4*i, v);
	}

	memcpy(block, s, 16);
}

int32_t aes_kw_unwrap(const uint8_t kek[16], uint8_t *data, uint32_t len, uint8_t *out)
{
	uint8_t a[8];
	uint8_t b[16];
	static const uint8_t kwiv[8] =
		{0xa6,0xa6,0xa6,0xa6,0xa6,0xa6,0xa6,0xa6};
	uint32_t n, i, j, t;

	if(len < 16 || (len & 7) || len > 48)
		return -1;
	n = (len>>3) - 1;

	memcpy(a, data, 8);
	/* compact R[] in place: R[i] = data[8+8*i] */
	memmove(data, data+8, n*8);

	t = 6*n;
	for(j=0;j<6;j++) {
		for(i=n;i>=1;i--) {
			memcpy(b, a, 8);
			/* per RFC 3394: B = D(K, (A XOR t) | R[i]) - the XOR
			 * with t goes into the DECRYPTION INPUT */
			b[7] ^= (uint8_t)(t & 0xff);
			b[6] ^= (uint8_t)((t >> 8) & 0xff);
			b[5] ^= (uint8_t)((t >> 16) & 0xff);
			memcpy(b+8, data+(i-1)*8, 8);
			aes128_decrypt_block(kek, b);
			memcpy(a, b, 8);              /* A = MSB64(B) */
			memcpy(data+(i-1)*8, b+8, 8); /* R[i] = LSB64(B) */
			t--;
		}
	}

	if(memcmp(a, kwiv, 8) != 0)
		return -1;
	if(out != data)
		memcpy(out, data, n*8);
	return (int32_t)(n*8);
}
